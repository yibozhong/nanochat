"""Heavy-Ball depth streams, optionally with anGPT-inspired scale correction.

Only residual arithmetic changes. The approximate variant uses coefficient-only
second moments, including hidden/velocity covariance; it is not a sphere model.
See research/connections/momentum/README.md for the approximation assumptions.
"""
import math

import torch
from torch import nn
from torch.nn import functional as F
from torch.utils.checkpoint import checkpoint

from nanochat.connection_model import ConnectionModel
from nanochat.gpt import norm


def state_dtype(x):
    return x if x.dtype in (torch.float32, torch.float64) else x.float()


def inverse_softplus(value):
    return value + math.log(-math.expm1(-value))


def approximate_momentum_step(h, v, moments, force, beta, gamma, eta, rms_floor):
    """Unit-second-moment innovation model; moments = (E[v²], E[h*v]).

    The innovation z is assumed uncorrelated with past h/v. The covariance
    generated by reusing v is retained exactly under that model. These two
    scalars depend only on coefficients, never on other tokens or minibatches.
    No stop-gradient: gradients pass through the moment recurrence as well.
    """
    h, v, force = state_dtype(h), state_dtype(v), state_dtype(force)
    # Smooth at nanochat's zero-initialized output projections. Derivative at
    # zero is 1/rms_floor, not an enormous 1/epsilon. RMS(z) <= 1, approaching
    # one once the branch RMS is large relative to the regularizer.
    z = force * torch.rsqrt(force.square().mean(-1, keepdim=True) + rms_floor**2)
    variance, covariance = moments.unbind()
    next_variance = beta.square() * variance + gamma.square()
    cross = beta * covariance
    scale = torch.rsqrt(1 + 2 * eta * cross + eta.square() * next_variance)
    u = beta * v + gamma * z
    next_h = (h + eta * u) * scale
    next_covariance = (cross + eta * next_variance) * scale
    # u is the carried velocity, not eta*u, the hidden displacement, or a
    # normalized vector. Both streams remain in the same Euclidean coordinates.
    return next_h, u, torch.stack((next_variance, next_covariance))


class HeavyBall(nn.Module):
    def __init__(self, config):
        super().__init__()
        b = config.momentum_beta_init
        # Preserve the existing Heavy-Ball parameter names/shapes and optimizer.
        self.raw = nn.Parameter(torch.tensor([
            math.log(b / (1 - b)), inverse_softplus(config.momentum_gamma_init),
            inverse_softplus(config.momentum_eta_init)], dtype=torch.float32))

    def coefficients(self):
        return self.raw[0].sigmoid(), F.softplus(self.raw[1]), F.softplus(self.raw[2])

    def forward(self, h, v, force):
        beta, gamma, eta = self.coefficients()
        u = beta * state_dtype(v) + gamma * state_dtype(force)
        return state_dtype(h) + eta * u, u


class ApproximateHeavyBall(HeavyBall):
    def __init__(self, config):
        super().__init__(config)
        self.rms_floor = config.an_force_rms_floor

    def forward(self, h, v, moments, force):
        return approximate_momentum_step(h, v, moments, force,
                                         *self.coefficients(), self.rms_floor)


def residual_update(config):
    return {'heavy_ball': HeavyBall, 'an_heavy_ball': ApproximateHeavyBall}[config.residual_mode](config)


class MomentumModel(ConnectionModel):
    def __init__(self, config):
        super().__init__(config)
        # Allocate after the backbone to preserve seed-matched initialization.
        self.velocity_embedding = None
        if config.velocity_init == 'token':
            self.velocity_embedding = nn.Embedding(config.vocab_size, config.width)
            nn.init.normal_(self.velocity_embedding.weight, std=config.velocity_embedding_std)

    def prepare(self, device='cuda', dtype=torch.bfloat16, compile_blocks=False):
        super().prepare(device, dtype, compile_blocks=False)
        if self.velocity_embedding is not None:
            self.velocity_embedding.to(dtype=dtype)
        if compile_blocks:
            # Preserve BF16 branch rounding at the FP32 residual boundary.
            self.compiled_steps = [torch.compile(self.block_step(b), dynamic=False, fullgraph=True,
                                   options={'emulate_precision_casts': True}) for b in self.blocks]
        return self

    def block_step(self, block):
        return block.an_momentum_forward if self.config.residual_mode == 'an_heavy_ball' else block.momentum_forward

    def hidden(self, idx, kv_cache=None):
        h = self.backbone(self.wte(idx), kv_cache, token_ids=idx)
        return norm(h.to(self.wte.weight.dtype))

    def initial_state(self, x, token_ids=None):
        h = state_dtype(norm(x))
        if self.velocity_embedding is None:
            return h, torch.zeros_like(h)
        if token_ids is None:
            raise ValueError('Token IDs are required for velocity embeddings')
        return h, state_dtype(self.velocity_embedding(token_ids))

    def initial_moments(self, h):
        # Independent embeddings at initialization. This remains a nominal
        # scale model during learning, not an estimate of observed statistics.
        variance = self.config.velocity_embedding_std**2 if self.velocity_embedding is not None else 0.
        return h.new_tensor([variance, 0.])

    def backbone(self, x, kv_cache=None, return_layers=False, token_ids=None):
        start = 0 if kv_cache is None else kv_cache.get_pos()
        if start + x.shape[1] > self.config.sequence_length:
            raise ValueError('Input exceeds configured context length')
        h, v = self.initial_state(x, token_ids)
        approximate = self.config.residual_mode == 'an_heavy_ball'
        state = (h, v, self.initial_moments(h)) if approximate else (h, v)
        cos, sin = self.cos[:, start:start+x.shape[1]], self.sin[:, start:start+x.shape[1]]
        states = [] if return_layers else None
        for i, b in enumerate(self.blocks):
            fn = self.compiled_steps[i] if self.compiled_steps is not None and kv_cache is None else self.block_step(b)
            if self.config.activation_checkpoint and self.training and torch.is_grad_enabled():
                if kv_cache is not None:
                    raise ValueError('Activation checkpointing cannot mutate a KV cache')
                state = checkpoint(fn, *state, cos, sin, use_reentrant=False)
            else:
                state = fn(*state, cos, sin, kv_cache)
            if return_layers:
                states.append(state[0])
        # All state is local to one token's depth traversal. Recompute the
        # coefficient-only moments per forward; no KV/checkpoint state is added.
        h = state[0]
        return (h, torch.stack(states, dim=2)) if return_layers else h

    @torch.no_grad()
    def residual_metrics(self):
        values = torch.stack([torch.stack(m.coefficients()) for b in self.blocks
                              for m in (b.attn_residual, b.mlp_residual)]).cpu()
        result = {}
        variance = self.config.velocity_embedding_std**2 if self.velocity_embedding is not None else 0.
        covariance = 0.
        for i, row in enumerate(values.tolist()):
            for name, value in zip(('beta', 'gamma', 'eta'), row):
                result[f'residual/sublayer_{i}/{name}'] = value
            if self.config.residual_mode == 'an_heavy_ball':
                beta, gamma, eta = row
                next_variance = beta**2 * variance + gamma**2
                cross = beta * covariance
                scale = (1 + 2*eta*cross + eta**2*next_variance)**-.5
                covariance = (cross + eta*next_variance)*scale
                variance = next_variance
                result[f'residual/sublayer_{i}/nominal_scale'] = scale
                result[f'residual/sublayer_{i}/nominal_hv_moment'] = covariance
        if self.velocity_embedding is not None:
            result['residual/velocity_embedding_rms'] = self.velocity_embedding.weight.float().square().mean().sqrt().item()
        return result
